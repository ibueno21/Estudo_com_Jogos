# Carregamento de variáveis de ambiente (.env)
#
# O arquivo .env (na raiz do projeto) guarda as credenciais que NÃO devem
# ficar no código-fonte (SECRET_KEY, senha do banco, etc.). Ele NÃO é
# versionado pelo git (veja o .gitignore).
# ---------------------------------------------------------------------------


def _load_env(env_path):
    """Lê um arquivo .env simples (CHAVE=valor) para dentro de os.environ."""
    if not env_path.exists():
        return
    with env_path.open('r', encoding='utf-8') as f:
        for linha in f:
            linha = linha.strip()
            # Ignora linhas vazias e comentários
            if not linha or linha.startswith('#') or '=' not in linha:
                continue
            chave, valor = linha.split('=', 1)
            chave = chave.strip()
            valor = valor.strip().strip('"').strip("'")
            # Não sobrescreve variáveis já definidas no ambiente real
            os.environ.setdefault(chave, valor)


_load_env(BASE_DIR / '.env')


